import {writeFileSync} from 'node:fs';
import {createGapAwareEngine} from '../gap-aware-composition.mjs';
const e=createGapAwareEngine();
await e.registerKnown({id:'A',revision:'r1',payload:{kind:'quantity',dimension:'data',unit:'MB',value:5}});
await e.registerGap({id:'G',revision:'r1',state:'INTENTIONALLY_OPEN',explanation_code:'KEEP_OPEN'});
await e.registerGap({id:'H',revision:'r1',state:'UNKNOWN'});
await e.registerGap({id:'R',revision:'r1',state:'REDACTED'});
const x=await e.compose({inputIds:['A','G','H'],rule:'quantity_sum',context:{target_unit:'MB'}});
const positive=[e.read('A'),e.read('G'),e.read('H'),e.read(x.id),e.read('R')];
const malicious=JSON.parse(JSON.stringify(e.read(x.id)));
malicious.packet.automatic_fill=true;
const fakeAck=JSON.parse(JSON.stringify(e.read(x.id)));
fakeAck.packet.real_ack='VERIFIED';
const fakeValue=JSON.parse(JSON.stringify(e.read('G')));
fakeValue.packet.value=0;
const fakeRestricted=JSON.parse(JSON.stringify(e.read('H')));
fakeRestricted.packet.state='REDACTED';
const bad=[malicious,fakeAck,fakeValue,fakeRestricted];
writeFileSync(process.argv[2]||'gap-fixtures.json',JSON.stringify({positive,bad},null,2));